#!/usr/bin/env -S swift -suppress-warnings
// Generates small, deterministic media fixtures for tests (docs/ARCHITECTURE.md §20) and verifies
// every file by reading it back with ImageIO / AVFoundation.
//
// Usage: scripts/make_test_media.swift [output-dir]   (or: swift scripts/make_test_media.swift …, which also
//        prints macOS 27 SDK deprecation warnings for AVAssetWriter; the project keeps the classic API, D-21)
// Default output: TestMedia/generated/fixtures (git-ignored).
//
// Safety: writes only inside the output directory. A non-empty directory is used only if it carries
// the marker file this script leaves behind; nothing outside the list below is ever touched.

import AVFoundation
import CoreGraphics
import Foundation
import ImageIO
import UniformTypeIdentifiers

// MARK: - Setup

let markerName = ".jglancer-generated"
let scriptDirectory = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
let output = (CommandLine.arguments.count > 1
    ? URL(fileURLWithPath: CommandLine.arguments[1])
    : scriptDirectory.appendingPathComponent("../TestMedia/generated/fixtures")).standardizedFileURL
let fileManager = FileManager.default

struct ScriptError: Error, CustomStringConvertible {
    let description: String
    init(_ description: String) {
        self.description = description
    }
}

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("error: \(message)\n".utf8))
    exit(1)
}

@MainActor
func prepareOutputDirectory() throws {
    if fileManager.fileExists(atPath: output.path) {
        let contents = try fileManager.contentsOfDirectory(atPath: output.path)
        if !contents.isEmpty, !contents.contains(markerName) {
            fail("\(output.path) is not empty and was not created by this script; refusing to write there")
        }
    }
    try fileManager.createDirectory(at: output, withIntermediateDirectories: true)
    try Data("Generated by scripts/make_test_media.swift. Safe to delete.\n".utf8)
        .write(to: output.appendingPathComponent(markerName))
}

/// Destination URL for a fixture; replaces a previous copy of the same fixture only.
@MainActor
func destination(_ relativePath: String) throws -> URL {
    let url = output.appendingPathComponent(relativePath)
    try fileManager.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
    if fileManager.fileExists(atPath: url.path) {
        try fileManager.removeItem(at: url)
    }
    return url
}

// MARK: - Images

let sRGB = CGColorSpace(name: CGColorSpace.sRGB) ?? CGColorSpaceCreateDeviceRGB()
let palette: [UInt32] = [0x101115, 0x2B3763, 0x7B9CF0, 0x5BD6A0, 0xF2C14E, 0xFF6B6B, 0xA4A7AF, 0xF4F4F1]

func fill(_ context: CGContext, _ hex: UInt32, _ rect: CGRect) {
    context.setFillColor(CGColor(
        srgbRed: CGFloat((hex >> 16) & 0xFF) / 255,
        green: CGFloat((hex >> 8) & 0xFF) / 255,
        blue: CGFloat(hex & 0xFF) / 255,
        alpha: 1
    ))
    context.fill(rect)
}

/// Draws the deterministic test pattern: color bands keyed by `seed`, a red square marking the
/// top-left corner of the stored pixels (to check orientation handling), and a diagonal.
func drawPattern(in context: CGContext, width: Int, height: Int, seed: Int) {
    let bands = palette.count
    for band in 0 ..< bands {
        let hex = palette[(band + seed) % bands]
        let bandWidth = CGFloat(width) / CGFloat(bands)
        fill(context, hex, CGRect(x: CGFloat(band) * bandWidth, y: 0, width: bandWidth + 1, height: CGFloat(height)))
    }
    let marker = CGFloat(min(width, height)) / 5
    fill(context, 0xFF0000, CGRect(x: 0, y: CGFloat(height) - marker, width: marker, height: marker))
    context.setStrokeColor(CGColor(gray: 1, alpha: 1))
    context.setLineWidth(CGFloat(max(2, min(width, height) / 60)))
    context.move(to: .zero)
    context.addLine(to: CGPoint(x: width, y: height))
    context.strokePath()
}

func makeImage(width: Int, height: Int, seed: Int, alpha: Bool = false) throws -> CGImage {
    let info = alpha ? CGImageAlphaInfo.premultipliedLast : CGImageAlphaInfo.noneSkipLast
    guard let context = CGContext(
        data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
        space: sRGB, bitmapInfo: info.rawValue
    ) else { throw ScriptError("cannot create bitmap context") }
    if alpha {
        context.clear(CGRect(x: 0, y: 0, width: width, height: height))
        context.addEllipse(in: CGRect(x: 0, y: 0, width: width, height: height))
        context.clip()
    }
    drawPattern(in: context, width: width, height: height, seed: seed)
    guard let image = context.makeImage() else { throw ScriptError("cannot render image") }
    return image
}

func encode(_ image: CGImage, as type: UTType, properties: [CFString: Any] = [:]) throws -> Data {
    let data = NSMutableData()
    guard let target = CGImageDestinationCreateWithData(data as CFMutableData, type.identifier as CFString, 1, nil) else {
        throw ScriptError("ImageIO cannot write \(type.identifier)")
    }
    var options = properties
    options[kCGImageDestinationLossyCompressionQuality] = 0.9
    CGImageDestinationAddImage(target, image, options as CFDictionary)
    guard CGImageDestinationFinalize(target) else { throw ScriptError("encoding \(type.identifier) failed") }
    return data as Data
}

func exif(captured: String, orientation: Int = 1) -> [CFString: Any] {
    [
        kCGImagePropertyOrientation: orientation,
        kCGImagePropertyExifDictionary: [kCGImagePropertyExifDateTimeOriginal: captured],
        kCGImagePropertyTIFFDictionary: [kCGImagePropertyTIFFMake: "jGlancer", kCGImagePropertyTIFFModel: "Fixture"],
    ]
}

// MARK: - Video and audio

@MainActor
func writeVideo(to url: URL, fileType: AVFileType, width: Int, height: Int, frames: Int, fps: Int32) async throws {
    let writer = try AVAssetWriter(outputURL: url, fileType: fileType)
    let input = AVAssetWriterInput(mediaType: .video, outputSettings: [
        AVVideoCodecKey: AVVideoCodecType.h264, AVVideoWidthKey: width, AVVideoHeightKey: height,
    ])
    input.expectsMediaDataInRealTime = false
    let adaptor = AVAssetWriterInputPixelBufferAdaptor(assetWriterInput: input, sourcePixelBufferAttributes: [
        kCVPixelBufferPixelFormatTypeKey as String: kCVPixelFormatType_32BGRA,
        kCVPixelBufferWidthKey as String: width,
        kCVPixelBufferHeightKey as String: height,
    ])
    writer.add(input)
    guard writer.startWriting() else { throw writer.error ?? ScriptError("cannot start writing \(url.lastPathComponent)") }
    writer.startSession(atSourceTime: .zero)
    for frame in 0 ..< frames {
        while !input.isReadyForMoreMediaData {
            try await Task.sleep(for: .milliseconds(2))
        }
        guard let pool = adaptor.pixelBufferPool else { throw ScriptError("no pixel buffer pool") }
        var pixelBuffer: CVPixelBuffer?
        CVPixelBufferPoolCreatePixelBuffer(nil, pool, &pixelBuffer)
        guard let pixelBuffer else { throw ScriptError("no pixel buffer") }
        CVPixelBufferLockBaseAddress(pixelBuffer, [])
        if let context = CGContext(
            data: CVPixelBufferGetBaseAddress(pixelBuffer), width: width, height: height, bitsPerComponent: 8,
            bytesPerRow: CVPixelBufferGetBytesPerRow(pixelBuffer), space: sRGB,
            bitmapInfo: CGImageAlphaInfo.premultipliedFirst.rawValue | CGBitmapInfo.byteOrder32Little.rawValue
        ) {
            drawPattern(in: context, width: width, height: height, seed: frame / 6)
            let bar = CGFloat(width) * CGFloat(frame) / CGFloat(frames)
            fill(context, 0xFFFFFF, CGRect(x: bar, y: 0, width: CGFloat(width) / 20, height: CGFloat(height)))
        }
        CVPixelBufferUnlockBaseAddress(pixelBuffer, [])
        guard adaptor.append(pixelBuffer, withPresentationTime: CMTime(value: CMTimeValue(frame), timescale: fps)) else {
            throw writer.error ?? ScriptError("cannot append frame \(frame)")
        }
    }
    input.markAsFinished()
    await writer.finishWriting()
    guard writer.status == .completed else { throw writer.error ?? ScriptError("writing \(url.lastPathComponent) failed") }
}

/// Writes a sine tone; the container and codec follow `settings` and the file extension.
func writeTone(to url: URL, settings: [String: Any], frequency: Double, seconds: Double, channels: Int) throws {
    let sampleRate = 44100.0
    let file = try AVAudioFile(forWriting: url, settings: settings, commonFormat: .pcmFormatFloat32, interleaved: false)
    let frameCount = AVAudioFrameCount(sampleRate * seconds)
    guard let buffer = AVAudioPCMBuffer(pcmFormat: file.processingFormat, frameCapacity: frameCount),
          let channelData = buffer.floatChannelData
    else { throw ScriptError("cannot allocate audio buffer") }
    buffer.frameLength = frameCount
    let fade = sampleRate * 0.05
    for channel in 0 ..< channels {
        let pitch = frequency * (channel == 0 ? 1 : 1.5)
        for index in 0 ..< Int(frameCount) {
            let time = Double(index) / sampleRate
            let envelope = min(1, Double(index) / fade, Double(Int(frameCount) - index) / fade)
            channelData[channel][index] = Float(0.4 * envelope * sin(2 * .pi * pitch * time))
        }
    }
    try file.write(from: buffer)
    // Close now: deallocation can be deferred by the autorelease pool, leaving the encoder unflushed
    // and the file unusable for compositions until the process exits.
    file.close()
}

func pcmSettings(channels: Int, bigEndian: Bool) -> [String: Any] {
    [
        AVFormatIDKey: kAudioFormatLinearPCM, AVSampleRateKey: 44100, AVNumberOfChannelsKey: channels,
        AVLinearPCMBitDepthKey: 16, AVLinearPCMIsFloatKey: false, AVLinearPCMIsBigEndianKey: bigEndian,
    ]
}

let aacSettings: [String: Any] = [
    AVFormatIDKey: kAudioFormatMPEG4AAC, AVSampleRateKey: 44100, AVNumberOfChannelsKey: 2, AVEncoderBitRateKey: 128_000,
]

func metadataItem(_ identifier: AVMetadataIdentifier, _ value: NSCopying & NSObjectProtocol, dataType: String? = nil) -> AVMetadataItem {
    let item = AVMutableMetadataItem()
    item.identifier = identifier
    item.value = value
    item.extendedLanguageTag = "und"
    if let dataType {
        item.dataType = dataType
    }
    return item
}

/// Copies `source` without re-encoding, adding iTunes metadata and cover art.
@MainActor
func tag(_ source: URL, into target: URL, title: String, artist: String, album: String, artwork: Data) async throws {
    guard let session = AVAssetExportSession(asset: AVURLAsset(url: source), presetName: AVAssetExportPresetPassthrough) else {
        throw ScriptError("cannot create export session")
    }
    session.metadata = [
        metadataItem(.iTunesMetadataSongName, title as NSString),
        metadataItem(.iTunesMetadataArtist, artist as NSString),
        metadataItem(.iTunesMetadataAlbum, album as NSString),
        metadataItem(.iTunesMetadataCoverArt, artwork as NSData, dataType: kCMMetadataBaseDataType_JPEG as String),
    ]
    try await session.export(to: target, as: .m4a)
}

/// Passthrough-exports `video` (plus optional `audio`) with a track transform; no re-encoding.
/// Two AVFoundation rules verified on macOS 27.2 (DECISIONS D-21): a source asset must outlive the use
/// of its tracks (else inserting fails with -12780), and PCM sources need precise timing (else -17770).
@MainActor
func compose(video: URL, audio: URL?, transform: CGAffineTransform, into target: URL, as fileType: AVFileType) async throws {
    let precise = [AVURLAssetPreferPreciseDurationAndTimingKey: true]
    let composition = AVMutableComposition(urlAssetInitializationOptions: precise)
    let videoAsset = AVURLAsset(url: video, options: precise)
    let duration = try await videoAsset.load(.duration)
    let range = CMTimeRange(start: .zero, duration: duration)
    guard let sourceVideo = try await videoAsset.loadTracks(withMediaType: .video).first,
          let videoTrack = composition.addMutableTrack(withMediaType: .video, preferredTrackID: kCMPersistentTrackID_Invalid)
    else { throw ScriptError("no video track in \(video.lastPathComponent)") }
    try videoTrack.insertTimeRange(range, of: sourceVideo, at: .zero)
    videoTrack.preferredTransform = transform
    let audioAsset = audio.map { AVURLAsset(url: $0, options: precise) }
    if let audioAsset, let audio {
        guard let sourceAudio = try await audioAsset.loadTracks(withMediaType: .audio).first,
              let audioTrack = composition.addMutableTrack(withMediaType: .audio, preferredTrackID: kCMPersistentTrackID_Invalid)
        else { throw ScriptError("no audio track in \(audio.lastPathComponent)") }
        try audioTrack.insertTimeRange(range, of: sourceAudio, at: .zero)
    }
    guard let session = AVAssetExportSession(asset: composition, presetName: AVAssetExportPresetPassthrough) else {
        throw ScriptError("cannot create export session")
    }
    try await session.export(to: target, as: fileType)
    withExtendedLifetime((videoAsset, audioAsset)) {}
}

// MARK: - Expectations and verification

enum Expectation {
    case image(type: UTType, width: Int, height: Int, orientation: Int = 1)
    case unreadable
    case av(video: (width: Int, height: Int)?, audio: Bool, seconds: Double, artwork: Bool = false)
    case notPlayable
    case notMedia
}

var fixtures: [(path: String, expectation: Expectation)] = []

@MainActor
func verify(_ path: String, _ expectation: Expectation) async -> String? {
    let url = output.appendingPathComponent(path)
    switch expectation {
    case let .image(type, width, height, orientation):
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
        else { return "ImageIO cannot read it" }
        let actualType = CGImageSourceGetType(source) as String? ?? "?"
        let actual = (
            properties[kCGImagePropertyPixelWidth] as? Int ?? -1,
            properties[kCGImagePropertyPixelHeight] as? Int ?? -1,
            properties[kCGImagePropertyOrientation] as? Int ?? 1
        )
        if actualType != type.identifier {
            return "type \(actualType), expected \(type.identifier)"
        }
        if actual != (width, height, orientation) {
            return "got \(actual), expected \((width, height, orientation))"
        }
        return CGImageSourceCreateImageAtIndex(source, 0, nil) == nil ? "does not decode" : nil
    case .unreadable:
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        return CGImageSourceGetType(source) == nil ? nil : "ImageIO recognizes it"
    case let .av(video, audio, seconds, artwork):
        let asset = AVURLAsset(url: url)
        do {
            let (playable, duration) = try await asset.load(.isPlayable, .duration)
            guard playable else { return "not playable" }
            if abs(duration.seconds - seconds) > 0.1 {
                return "duration \(duration.seconds), expected \(seconds)"
            }
            let videoTracks = try await asset.loadTracks(withMediaType: .video)
            let audioTracks = try await asset.loadTracks(withMediaType: .audio)
            if audio != !audioTracks.isEmpty {
                return "audio track presence is \(!audioTracks.isEmpty)"
            }
            if let video {
                guard let track = videoTracks.first else { return "no video track" }
                let (size, transform) = try await track.load(.naturalSize, .preferredTransform)
                let display = size.applying(transform)
                if (Int(abs(display.width)), Int(abs(display.height))) != video {
                    return "displays \(display), expected \(video)"
                }
            } else if !videoTracks.isEmpty {
                return "unexpected video track"
            }
            if artwork {
                let items = try await asset.load(.commonMetadata)
                let covers = AVMetadataItem.metadataItems(from: items, filteredByIdentifier: .commonIdentifierArtwork)
                guard let cover = covers.first, let data = try await cover.load(.dataValue),
                      CGImageSourceCreateWithData(data as CFData, nil) != nil
                else { return "no readable cover art" }
            }
            return nil
        } catch {
            return "AVFoundation error: \(error.localizedDescription)"
        }
    case .notPlayable:
        let playable = await (try? AVURLAsset(url: url).load(.isPlayable)) ?? false
        return playable ? "AVFoundation can play it" : nil
    case .notMedia:
        let type = UTType(filenameExtension: url.pathExtension)
        let isMedia = [UTType.image, .movie, .audio].contains { type?.conforms(to: $0) == true }
        return isMedia ? "classified as media" : nil
    }
}

// MARK: - Generation

/// Runs one generation step, labeling any error with the step name.
@MainActor
func step(_ label: String, _ body: () async throws -> Void) async throws {
    do {
        try await body()
    } catch {
        throw ScriptError("\(label): \(error)")
    }
}

@MainActor
func write(_ data: Data, _ path: String, _ expectation: Expectation) throws {
    try data.write(to: destination(path))
    fixtures.append((path, expectation))
}

@MainActor
func generate() async throws {
    // Photos
    let landscape = try makeImage(width: 640, height: 480, seed: 0)
    let jpeg = try encode(landscape, as: .jpeg, properties: exif(captured: "2024:05:17 10:30:00"))
    try write(jpeg, "photo_landscape.jpg", .image(type: .jpeg, width: 640, height: 480))
    try write(
        encode(landscape, as: .jpeg, properties: exif(captured: "2024:05:17 10:31:00", orientation: 6)),
        "photo_orientation6.jpg", .image(type: .jpeg, width: 640, height: 480, orientation: 6)
    )
    try write(encode(makeImage(width: 640, height: 480, seed: 2), as: .heic, properties: exif(captured: "2024:05:17 10:32:00")),
              "photo.heic", .image(type: .heic, width: 640, height: 480))
    let png = try encode(makeImage(width: 320, height: 240, seed: 3, alpha: true), as: .png)
    try write(png, "photo_alpha.png", .image(type: .png, width: 320, height: 240))
    try write(encode(makeImage(width: 64, height: 48, seed: 4), as: .tiff), "photo.tiff", .image(type: .tiff, width: 64, height: 48))
    try write(encode(makeImage(width: 64, height: 48, seed: 5), as: .gif), "photo.gif", .image(type: .gif, width: 64, height: 48))
    try write(jpeg, "UPPERCASE.JPG", .image(type: .jpeg, width: 640, height: 480))
    try write(png, "png_named_as.jpg", .image(type: .png, width: 320, height: 240))
    try write(jpeg, "no_extension", .image(type: .jpeg, width: 640, height: 480))

    // Odd names
    for name in [
        "name with spaces.jpg", "кириллица фото.jpg", "unicode 📷.jpg", "cafe\u{0301} (NFD).jpg",
        "#hash %percent &amp.jpg", "semi;colon,comma.jpg", "-leading-dash.jpg",
        "long_" + String(repeating: "a", count: 200) + ".jpg",
    ] {
        try write(jpeg, "odd names/\(name)", .image(type: .jpeg, width: 640, height: 480))
    }

    // Structure: nesting, hidden items and a package the scanner must skip.
    try write(jpeg, "nested/level2/level3/deep.jpg", .image(type: .jpeg, width: 640, height: 480))
    try write(jpeg, ".hidden.jpg", .image(type: .jpeg, width: 640, height: 480))
    try write(jpeg, ".hidden_folder/inside.jpg", .image(type: .jpeg, width: 640, height: 480))
    try write(jpeg, "Skipped.bundle/inside.jpg", .image(type: .jpeg, width: 640, height: 480))

    // Broken and non-media files
    // ImageIO reports a truncated JPEG as complete and decodes it, filling the missing rows (DECISIONS D-21).
    try write(jpeg.prefix(jpeg.count / 3), "corrupt_truncated.jpg", .image(type: .jpeg, width: 640, height: 480))
    var generator: UInt64 = 0x9E37_79B9_7F4A_7C15
    let garbage = Data((0 ..< 4096).map { _ in
        generator = generator &* 6_364_136_223_846_793_005 &+ 1_442_695_040_888_963_407
        return UInt8(truncatingIfNeeded: generator >> 33)
    })
    try write(garbage, "corrupt_garbage.jpg", .unreadable)
    try write(Data(), "empty.mp4", .notPlayable)
    try write(Data([0x1A, 0x45, 0xDF, 0xA3]) + Data("matroska-not-really".utf8) + garbage.prefix(512), "unsupported.mkv", .notPlayable)
    try write(Data("Not media. The scanner must ignore this file.\n".utf8), "notes.txt", .notMedia)

    // Audio
    try writeTone(to: destination("tone_440_mono.wav"), settings: pcmSettings(channels: 1, bigEndian: false),
                  frequency: 440, seconds: 2, channels: 1)
    fixtures.append(("tone_440_mono.wav", .av(video: nil, audio: true, seconds: 2)))
    try writeTone(to: destination("tone_stereo.aiff"), settings: pcmSettings(channels: 2, bigEndian: true),
                  frequency: 330, seconds: 2, channels: 2)
    fixtures.append(("tone_stereo.aiff", .av(video: nil, audio: true, seconds: 2)))
    let untagged = try destination("work/untagged.m4a")
    try writeTone(to: untagged, settings: aacSettings, frequency: 523.25, seconds: 3, channels: 2)
    let cover = try encode(makeImage(width: 300, height: 300, seed: 6), as: .jpeg)
    try await step("tag tone_with_cover.m4a") {
        try await tag(untagged, into: destination("tone_with_cover.m4a"),
                      title: "Fixture Tone", artist: "jGlancer", album: "Test Media", artwork: cover)
    }
    fixtures.append(("tone_with_cover.m4a", .av(video: nil, audio: true, seconds: 3, artwork: true)))

    // Video
    try await step("write clip.mov") {
        try await writeVideo(to: destination("clip.mov"), fileType: .mov, width: 320, height: 240, frames: 60, fps: 30)
    }
    fixtures.append(("clip.mov", .av(video: (320, 240), audio: false, seconds: 2)))
    try await step("compose clip_with_audio.mp4") {
        try await compose(video: output.appendingPathComponent("clip.mov"), audio: untagged, transform: .identity,
                          into: destination("clip_with_audio.mp4"), as: .mp4)
    }
    fixtures.append(("clip_with_audio.mp4", .av(video: (320, 240), audio: true, seconds: 2)))
    // Portrait as phones record it: landscape pixels plus a 90° track transform.
    let rotate90 = CGAffineTransform(a: 0, b: 1, c: -1, d: 0, tx: 240, ty: 0)
    try await step("compose portrait_rotated.mov") {
        try await compose(video: output.appendingPathComponent("clip.mov"), audio: nil, transform: rotate90,
                          into: destination("portrait_rotated.mov"), as: .mov)
    }
    fixtures.append(("portrait_rotated.mov", .av(video: (240, 320), audio: false, seconds: 2)))
    try fileManager.removeItem(at: output.appendingPathComponent("work"))

    // Deterministic modification dates, one hour apart, so date sorting is testable.
    let base = Date(timeIntervalSince1970: 1_715_940_000) // 2024-05-17 10:00 UTC
    for (index, fixture) in fixtures.enumerated() {
        try fileManager.setAttributes(
            [.modificationDate: base.addingTimeInterval(Double(index) * 3600)],
            ofItemAtPath: output.appendingPathComponent(fixture.path).path
        )
    }
}

// MARK: - Main

do {
    try prepareOutputDirectory()
    try await generate()
} catch {
    fail("\(error)")
}

var failures = 0
for fixture in fixtures {
    let problem = await verify(fixture.path, fixture.expectation)
    if problem != nil {
        failures += 1
    }
    let shown = fixture.path.count > 60 ? String(fixture.path.prefix(57)) + "..." : fixture.path
    print("\(problem == nil ? "ok  " : "FAIL") \(shown.padding(toLength: 60, withPad: " ", startingAt: 0)) \(problem ?? "")")
}

print("\(fixtures.count) fixtures in \(output.path), \(failures) failed verification")
exit(failures == 0 ? 0 : 1)
